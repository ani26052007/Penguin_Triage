OUTPUT = TASK.reference.mimic.output
GAINS = {"right_arm": {"stiffness": 400.0}}


def progress(s: int, a: int) -> str:
    return f"{s}/{a} ({100.0 * s / a:.1f}%) successful demos generated by mimic after 0.4 minutes"


def fixture_log(outcomes) -> str:
    """FIXTURE Mimic log: Isaac Sim noise, then one cumulative progress line per attempt."""
    lines = ["[INFO] Starting SimulationApp", "[Warning] [omni.physx] some warning", "Loading input file ..."]
    s = 0
    for a, ok in enumerate(outcomes, 1):
        s += ok
        lines += [f"[INFO] env 0 finished attempt", progress(s, a)]
    lines.append("[INFO] Simulation closed")
    return "\n".join(lines) + "\n"


@dataclass
class FakeMimicRunner(ArenaRunner):
    """Writes ``log`` (or ``fixture_log(outcomes)``) instead of running Mimic; ``crash`` fails like a crash."""
    outcomes: tuple = (True, True, False, True)
    log: str | None = None
    crash: bool = False
    calls: list = field(default_factory=list)

    def run(self, inv: RunInvocation) -> None:
        self.calls.append(inv)
        if self.crash:
            raise ArenaRunError("Mimic exited with 1 (fake)", returncode=1, log_path=inv.log_path)
        inv.log_path.write_text(self.log if self.log is not None else fixture_log(self.outcomes), encoding="utf-8")


def make_reference(tmp_path, *, outcomes=(True, True, False, True), datasets=True, **kw):
    tmp_path.mkdir(parents=True, exist_ok=True)
    source = tmp_path / "annotated.hdf5"
    source.write_bytes(b"FIXTURE")
    cfg = backend_config(tmp_path, tmp_path, datasets={TASK.reference.mimic.source_dataset: source} if datasets else {})
    runner = FakeMimicRunner(outcomes=tuple(outcomes), **kw)
    return MimicReference(cfg, TASK, runner=runner), runner, source


def variations(scene=DARK):
    from vla_isaac.scene.factors import FactorTable
    return FactorTable.load(TASK.factor_table).assignments(scene)


# ---- parse Mimic's log --------------------------------------------------------------------------

def test_the_log_gives_each_attempt_in_order_and_the_totals():
    outcomes, totals = trial_outcomes(fixture_log([True, False, False, True, True]), OUTPUT)
    assert outcomes == [True, False, False, True, True] and totals == (3, 5)
    repeated = fixture_log([True, False]) + progress(1, 2) + "\n"          # the same count printed again
    assert trial_outcomes(repeated, OUTPUT) == ([True, False], (1, 2))
    assert trial_outcomes("nothing here\n", OUTPUT) == ([], (0, 0))


def test_a_log_that_cannot_order_the_attempts_is_an_error():
    with pytest.raises(MimicOutputError, match="mixed outcomes"):
        trial_outcomes(progress(1, 1) + "\n" + progress(2, 4) + "\n", OUTPUT)   # 3 attempts, 1 success: order?
    assert trial_outcomes(progress(1, 1) + "\n" + progress(1, 3) + "\n", OUTPUT)[0] == [True, False, False]
    with pytest.raises(MimicOutputError, match="not cumulative"):
        trial_outcomes(progress(1, 1) + "\n" + progress(0, 2) + "\n", OUTPUT)


def test_the_progress_pattern_must_name_successes_and_attempts():
    with pytest.raises(ConfigError, match="named groups"):
        MimicOutput(r"(\d+)/(\d+)")


# ---- one result per seed, in trial order, unpaired -------------------------------------------------

def test_one_result_per_requested_seed_in_trial_order_and_unpaired(tmp_path):
    ref, runner, _ = make_reference(tmp_path, outcomes=(True, False, True))
    out = ref.run(DARK, REF_RAW, [40, 10, 7], variations=variations())
    assert [(r.seed, r.success, r.logs["trial_index"]) for r in out] == [(40, True, 0), (10, False, 1), (7, True, 2)]
    assert all(r.logs["paired"] is False and r.logs["reference"] == "mimic" for r in out)
    meta = json.loads(Path(out[0].logs["paths"]["vla_meta"]).read_text())
    assert meta["trials"] == [True, False, True] and meta["paired"] is False and meta["seeds"] == [40, 10, 7]


def test_extra_attempts_are_counted_but_only_the_first_n_are_the_trials(tmp_path):
    ref, _, _ = make_reference(tmp_path, outcomes=(False, True, False, True, True))   # guarantee: 3 successes
    out = ref.run(NOMINAL, REF_RAW, [0, 1, 2], variations={})
    assert [r.success for r in out] == [False, True, False] and {r.logs["attempts_total"] for r in out} == {5}


def test_fewer_attempts_than_seeds_or_no_log_is_an_error(tmp_path):
    ref, _, _ = make_reference(tmp_path, outcomes=(True, True))
    with pytest.raises(MimicOutputError, match="2 attempts in the log, 3 trials"):
        ref.run(NOMINAL, REF_RAW, [0, 1, 2], variations={})
    ref, _, _ = make_reference(tmp_path / "b", crash=True)
    with pytest.raises(ArenaRunError):
        ref.run(NOMINAL, REF_RAW, [0], variations={})


# ---- the command: RAW, stock environment, scene variations, local source --------------------------

def test_the_command_is_generate_dataset_on_the_stock_environment_with_the_scene_variations(tmp_path):
    ref, runner, source = make_reference(tmp_path, outcomes=(True,) * 3)
    ref.run(DARK, REF_RAW, [0, 1, 2], variations=variations())
    argv = list(runner.calls[0].argv)
    m = TASK.reference.mimic
    assert argv[1].endswith("isaaclab_mimic/generate_dataset.py")
    assert argv[argv.index("--generation_num_trials") + 1] == "3" and argv[argv.index("--input_file") + 1] == str(source)
    assert argv[argv.index("--task") + 1] == "put_item_in_fridge_and_close_door"
    assert argv[argv.index("--embodiment") + 1] == "gr1_pink" and "--mimic" in argv
    assert argv[argv.index("--external_callback") + 1] == m.external_callback
    overrides = [hydra_override(k, v) for k, v in variations().items()]
    assert overrides and argv[-len(overrides):] == overrides             # the scene's variations, last
    assert "light.intensity.sampler_cfg.low=[100.0]" in overrides


def test_the_reference_never_gets_the_actuated_launcher_or_the_codes_gains(tmp_path):
    rig = make_backend(tmp_path, eval_config=with_eval(env={"actuator_overrides": GAINS}))
    source = tmp_path / "annotated.hdf5"
    source.write_bytes(b"FIXTURE")
    runner = FakeMimicRunner(outcomes=(True, False))
    ref = MimicReference(replace(rig.backend.cfg, datasets={TASK.reference.mimic.source_dataset: source}), TASK,
                         runner=runner)
    rig.backend.reference = ref
    out = rig.backend.run(DARK, rig.code(), REF_RAW, [3, 9], Mode.CLEAN)
    assert [r.seed for r in out] == [3, 9] and not rig.runner.calls and not rig.servers
    inv = runner.calls[0]
    text = " ".join(inv.argv) + " " + json.dumps(dict(inv.env))
    for banned in ("external_environment_class_path", "vla_isaac", TASK.actuated_environment_type, "stiffness",
                   ENV_OVERRIDES, ENV_BASE, ENV_NAME, "PYTHONPATH", str(rig.backend.cfg.output_root / "work")):
        assert banned not in text, banned
    assert inv.argv[inv.argv.index("--task") + 1] == TASK.environment["type"]
    policy = rig.backend.plan_run(DARK, rig.code(), POLICY, Mode.CLEAN, 0, 2, workdir=tmp_path)
    assert policy.actuated and ENV_OVERRIDES in policy.invocation.env        # the policy does get them


def test_without_a_local_source_dataset_the_run_is_refused_and_nothing_is_downloaded(tmp_path):
    ref, runner, _ = make_reference(tmp_path, datasets=False)
    with pytest.raises(MimicConfigError, match="V-mimic-source"):
        ref.run(NOMINAL, REF_RAW, [0], variations={})
    ref, runner2, source = make_reference(tmp_path / "b")
    source.unlink()
    with pytest.raises(MimicConfigError, match="is not at"):
        ref.run(NOMINAL, REF_RAW, [0], variations={})
    assert not runner.calls and not runner2.calls


def test_only_the_raw_reference_runs(tmp_path):
    ref, runner, _ = make_reference(tmp_path)
    with pytest.raises(ReplayUnavailable):
        ref.run(NOMINAL, REF_WRAP, [0], variations={})
    with pytest.raises(NotImplementedError):                    # G3 stays deferred (decision 3)
        ref.run(NOMINAL, REF_WRAP, [0], variations={})
    with pytest.raises(ValueError, match="RAW reference"):
        ref.run(NOMINAL, POLICY, [0], variations={})
    with pytest.raises(MimicConfigError, match="not this task's Mimic"):
        ref.run(NOMINAL, ActorRef(ActorKind.REFERENCE, "scripted", ActionPipeline.RAW), [0], variations={})
    assert not runner.calls


def test_the_backend_serves_raw_reference_seeds_through_the_cache(tmp_path):
    rig = make_backend(tmp_path)
    ref, runner, _ = make_reference(tmp_path / "ref", outcomes=(True, False, True))
    rig.backend.reference = ref
    cached = CachedBackend(rig.backend, RolloutCache())
    first = cached.run(NOMINAL, rig.code(), REF_RAW, [0, 1, 2], Mode.CLEAN)
    again = cached.run(NOMINAL, rig.code(), REF_RAW, [0, 1, 2], Mode.CLEAN)
    assert first == again and len(runner.calls) == 1 and [r.success for r in first] == [True, False, True]


