# ---- the command: RAW, stock environment, scene variations, local source --------------------------

def test_the_command_is_generate_dataset_on_the_stock_environment_with_the_scene_variations(tmp_path):
    ref, runner, source = make_reference(tmp_path, outcomes=(True,) * 3)
    ref.run(DARK, REF_RAW, [0, 1, 2], variations=variations())
    argv = list(runner.calls[0].argv)
    m = TASK.reference.mimic
    assert argv[1].endswith("isaaclab_mimic/generate_dataset.py")
    assert argv[argv.index("--generation_num_trials") + 1] == "3" and argv[argv.index("--input_file") + 1] == str(source)
    assert argv[argv.index("--task") + 1] == "put_item_in_fridge_and_close_door"
    assert argv[argv.index("--embodiment") + 1] == "gr1_pink" and "--mimic" in argv
    assert argv[argv.index("--external_callback") + 1] == m.external_callback
    overrides = [hydra_override(k, v) for k, v in variations().items()]
    assert overrides and argv[-len(overrides):] == overrides             # the scene's variations, last
    assert "light.intensity.sampler_cfg.low=[100.0]" in overrides


def test_the_reference_never_gets_the_actuated_launcher_or_the_codes_gains(tmp_path):
    rig = make_backend(tmp_path, eval_config=with_eval(env={"actuator_overrides": GAINS}))
    source = tmp_path / "annotated.hdf5"
    source.write_bytes(b"FIXTURE")
    runner = FakeMimicRunner(outcomes=(False,) * 3 + (True,) + (False,) * 5 + (False,))
    ref = MimicReference(replace(rig.backend.cfg, datasets={TASK.reference.mimic.source_dataset: source}), TASK,
                         runner=runner)
    rig.backend.reference = ref
    out = rig.backend.run(DARK, rig.code(), REF_RAW, [3, 9], Mode.CLEAN)
    assert [r.seed for r in out] == [3, 9] and not rig.runner.calls and not rig.servers
    inv = runner.calls[0]
    text = " ".join(inv.argv) + " " + json.dumps(dict(inv.env))
    for banned in ("external_environment_class_path", "vla_isaac", TASK.actuated_environment_type, "stiffness",
                   ENV_OVERRIDES, ENV_BASE, ENV_NAME, "PYTHONPATH", str(rig.backend.cfg.output_root / "work")):
        assert banned not in text, banned
    assert inv.argv[inv.argv.index("--task") + 1] == TASK.environment["type"]
    policy = rig.backend.plan_run(DARK, rig.code(), POLICY, Mode.CLEAN, 0, 2, workdir=tmp_path)
    assert policy.actuated and ENV_OVERRIDES in policy.invocation.env        # the policy does get them


