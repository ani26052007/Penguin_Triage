# ---- qualification: Wilson lower bound vs threshold (ISSUES #5) ----------------------------------

def trials(k: int, n: int) -> list[EpisodeResult]:
    return [EpisodeResult(i, i < k) for i in range(n)]


def test_the_rule_uses_the_wilson_lower_bound_not_the_raw_rate():
    rule = TASK.reference.qualification
    assert (rule.threshold, rule.confidence) == (0.8, 0.95)
    full = qualify(trials(20, 20), rule, NOMINAL.key())
    assert full.qualified and full.evidence() is None and full.lower == pytest.approx(0.8389, abs=1e-3)
    one_miss = qualify(trials(19, 20), rule, NOMINAL.key())
    assert 19 / 20 >= rule.threshold and not one_miss.qualified      # the raw rate passes, the bound does not
    assert one_miss.lower == pytest.approx(0.7639, abs=1e-3)
    assert qualify(trials(48, 50), rule, NOMINAL.key()).qualified     # more trials: the bound tightens


def test_the_threshold_and_confidence_are_configurable():
    assert qualify(trials(19, 20), QualificationRule(0.7), "c").qualified
    assert not qualify(trials(19, 20), QualificationRule(0.7, confidence=0.999), "c").qualified
    with pytest.raises(ConfigError):
        QualificationRule(1.5)
    with pytest.raises(ValueError):
        qualify([], QualificationRule(0.8), "c")


def test_unqualified_evidence_is_reference_unqualified_and_routes_to_row_2():
    e = qualify(trials(12, 20), TASK.reference.qualification, DARK.key()).evidence()
    assert (e.signal, e.source, e.strength) == (V.SIG_REFERENCE_UNQUALIFIED, "reference_qualification", 1.0)
    assert "12 of 20" in e.detail and "lower bound" in e.detail
    code, ref = CodeRef("c0"), ActorRef(ActorKind.REFERENCE, "mimic-gr1_pink", ActionPipeline.RAW)

    def rep(rid, outcome):
        return ReplayResult(rid, DARK, code, ref if rid == V.R_C1 else POLICY, Mode.CLEAN, (EpisodeResult(0, True),),
                            outcome)
    table = [rep(V.R_STAGE0, Outcome.NO_EFFECT), rep(V.R_STAGE2_NOMINAL, Outcome.RESTORED),
             rep(V.R_C1, Outcome.RESTORED), rep(V.restore_id("lighting.intensity"), Outcome.NO_EFFECT),
             rep(V.R_C_ALL, Outcome.NO_EFFECT)]
    assert decide([e], table).row == 2 and decide([], table).row != 2


